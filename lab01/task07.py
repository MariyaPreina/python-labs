# Задача 7.
# Даны три точки A, B, C на числовой оси.
# Найти длины отрезков AC и BC и их сумму.

a = float(input("Введите координату точки A: "))
b = float(input("Введите координату точки B: "))
c = float(input("Введите координату точки C: "))

#расстояние между двумя точками на числовой оси — это модуль разности их координат
ac = abs(c - a)
bc = abs(c - b)
total = ac + bc

print("Длина AC:", ac)
print("Длина BC:", bc)
print("Сумма длин:", total)
