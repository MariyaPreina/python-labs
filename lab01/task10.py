# Задача 10.
# Даны координаты трёх вершин треугольника:
# (x1, y1), (x2, y2), (x3, y3).
# Найти его периметр и площадь.

x1 = float(input("Введите x1: "))
y1 = float(input("Введите y1: "))
x2 = float(input("Введите x2: "))
y2 = float(input("Введите y2: "))
x3 = float(input("Введите x3: "))
y3 = float(input("Введите y3: "))

#a, b, c — длины сторон треугольника - расстояние между двумя вершинами (корень из суммы разности квадратов)
a = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5
b = ((x3 - x2) ** 2 + (y3 - y2) ** 2) ** 0.5
c = ((x1 - x3) ** 2 + (y1 - y3) ** 2) ** 0.5
p = a + b + c
#площадь по координатам вершин.
s = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2

print("Периметр:", p)
print("Площадь:", s)
