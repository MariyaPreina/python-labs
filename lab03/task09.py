# Задача 9.
# Начальный вклад равен 1000 руб. Каждый месяц вклад увеличивается
# на P процентов от имеющейся суммы (P — вещественное, 0 < P < 25).
# Определить, через сколько месяцев вклад превысит 1100 руб.
# Вывести количество месяцев K и итоговый размер вклада S.

p = float(input("Введите P (0 < P < 25): "))

# количество прошедших месяцев
k = 0
# текущая сумма
s = 1000
while s <= 1100:
    s = s + s * p / 100
    k = k + 1

print("Количество месяцев:", k)
print("Итоговый размер вклада:", s)
