# Задача 8.
# Дано целое число N (> 1). Вывести наименьшее целое число K,
# для которого сумма 1 + 2 + … + K больше или равна N, и саму сумму.

n = int(input("Введите N (> 1): "))

k = 0
total = 0
# Останавливаемся при первом достижении N: поэтому K минимально.
while total < n:
    k = k + 1
    total = total + k

print("K:", k)
print("Сумма:", total)
