# Задача 2.
# Дано целое число N (> 0).
# Найти произведение 1.1 · 1.2 · 1.3 · … (N сомножителей).

n = int(input("Введите N (> 0): "))

# Начинаем с 1: начальный ноль обнулил бы всё произведение.
product = 1
i = 1
while i <= n:
    factor = 1 + i / 10
    product = product * factor
    i = i + 1

print("Произведение:", product)
