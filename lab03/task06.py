# Задача 6.
# Даны целые положительные числа A и B (A < B).
# Вывести все целые числа от A до B включительно.
# Каждое число выводится столько раз, каково его значение
# (например, число 3 выводится 3 раза).

a = int(input("Введите A (> 0): "))
b = int(input("Введите B (> A): "))

number = a
while number <= b:
    # Для каждого нового числа отсчёт повторений начинается заново.
    repeat = 1
    while repeat <= number:
        print(number)
        repeat = repeat + 1
    number = number + 1
