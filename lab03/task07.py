# Задача 7.
# Даны положительные числа A и B (A > B). На отрезке длины A
# размещено максимально возможное количество отрезков длины B
# без наложений. Не используя умножение и деление,
# найти длину незанятой части отрезка A.

from decimal import Decimal

# Десятичные числа помогают избежать двоичной погрешности, например для 0.3 и 0.1.
a = Decimal(input("Введите A (> 0): "))
b = Decimal(input("Введите B (0 < B < A): "))

remainder = a
# Равенство тоже учитывается: последний отрезок может заполнить остаток целиком.
while remainder >= b:
    remainder = remainder - b

print("Длина незанятой части:", remainder)
