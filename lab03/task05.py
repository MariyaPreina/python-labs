# Задача 5.
# Дано вещественное число A и целое число N (> 0).
# Используя один цикл, найти значение 1 − A + A² − A³ + … ± Aᴺ.
# Условный оператор не использовать.

a = float(input("Введите A: "))
n = int(input("Введите N (> 0): "))

# Умножение на -A сразу формирует следующее слагаемое с нужным знаком.
# Текущее слагаемое с учётом знака
term = 1
# Накопленная сумма
total = 1
# Номер шага
i = 1
while i <= n:
    term = term * (-a)
    total = total + term
    i = i + 1

print("Значение выражения:", total)
