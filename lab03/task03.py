# Задача 3.
# Дано целое число N (> 0). Найти квадрат данного числа,
# используя формулу N² = 1 + 3 + 5 + … + (2 · N − 1).
# После добавления каждого слагаемого выводить текущее значение суммы.

n = int(input("Введите N (> 0): "))

square = 0
i = 1
while i <= n:
    # После i сложений сумма равна i².
    square = square + (2 * i - 1)
    print("Текущая сумма:", square)
    i = i + 1
