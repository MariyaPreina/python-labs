# Задача 4.
# Дано вещественное число A и целое число N (> 0).
# Используя один цикл, найти сумму 1 + A + A² + A³ + … + Aᴺ.

a = float(input("Введите A: "))
n = int(input("Введите N (> 0): "))

#текущая степень числа A.
power = 1
#накопленная сумма
total = 1
#номер степени, которую сейчас вычисляем
i = 1
while i <= n:
    power = power * a
    total = total + power
    i = i + 1

print("Сумма:", total)
