# Задача 4.
# Дано вещественное число A и целое число N (> 0).
# Используя один цикл, найти сумму 1 + A + A² + A³ + … + Aᴺ.

a = float(input("Введите A: "))
n = int(input("Введите N (> 0): "))

# Единица — первое слагаемое A в нулевой степени.
power = 1
total = 1
i = 1
while i <= n:
    # Получаем следующую степень из предыдущей одним умножением.
    power = power * a
    total = total + power
    i = i + 1

print("Сумма:", total)
