# Задача 10.
# Даны целые положительные числа A и B. Найти их наибольший
# общий делитель (НОД), используя алгоритм Евклида.

a = int(input("Введите A (> 0): "))
b = int(input("Введите B (> 0): "))

# НОД(a, b) равен НОД(b, a % b): общие делители не меняются.
while b != 0:
    remainder = a % b
    a = b
    b = remainder

# При нулевом остатке в a остаётся последний ненулевой делитель.
print("НОД:", a)
