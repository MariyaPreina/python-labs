# Задача 10.
# Дан целочисленный массив размера N, содержащий ровно два одинаковых
# элемента. Найти их номера и вывести в порядке возрастания.


numbers = list(map(int, input("Введите элементы массива через пробел: ").split()))
n = len(numbers)
if n < 2:
    print("Требуется не менее 2 элементов.")
else:
    found = False
    for i in range(n - 1):
        # j всегда больше i: пару не сравниваем дважды, номера уже возрастают.
        for j in range(i + 1, n):
            if numbers[i] == numbers[j]:
                print("Номера одинаковых элементов:", i + 1, j + 1)
                found = True
                break
        # Первый break завершил только внутренний цикл; завершаем и внешний.
        if found:
            break
    if not found:
        print("Одинаковых элементов нет.")
