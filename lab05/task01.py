# Задача 1.
# Дано целое N > 0. Сформировать и вывести массив из N первых
# положительных нечётных чисел: 1, 3, 5, ... .


n = int(input("Введите N (> 0): "))
if n <= 0:
    print("N должно быть положительным.")
else:
    numbers = []
    for i in range(n):
        numbers.append(2 * i + 1)
    print("Массив:", numbers)
