# Задача 6.
# Дано целое число в диапазоне 1–999. Вывести его строку-описание
# вида «четное двузначное число», «нечетное трехзначное число» и т. д.

number = int(input("Введите целое число от 1 до 999: "))

if number % 2 == 0:
    parity = "четное"
else:
    parity = "нечетное"

if number < 10:
    digits = "однозначное"
elif number < 100:
    digits = "двузначное"
else:
    digits = "трехзначное"

print(parity + " " + digits + " число")
