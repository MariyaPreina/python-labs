# Задача 3.
# На плоскости расположены три точки: A, B, C. Определить, какая
# из двух последних точек (B или C) расположена ближе к A,
# и вывести эту точку и её расстояние от точки A.

ax = float(input("Введите x точки A: "))
ay = float(input("Введите y точки A: "))
bx = float(input("Введите x точки B: "))
by = float(input("Введите y точки B: "))
cx = float(input("Введите x точки C: "))
cy = float(input("Введите y точки C: "))

#вычисляем два расстояния по формуле расстояния между точками
ab = ((bx - ax) ** 2 + (by - ay) ** 2) ** 0.5
ac = ((cx - ax) ** 2 + (cy - ay) ** 2) ** 0.5

if ab < ac:
    print("Ближе точка B:", bx, by)
    print("Расстояние:", ab)
elif ac < ab:
    print("Ближе точка C:", cx, cy)
    print("Расстояние:", ac)
else:
    print("Точки B и C равноудалены от A.")
    print("Расстояние:", ab)
