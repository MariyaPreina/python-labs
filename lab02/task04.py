# Задача 4.
# Даны координаты точки, не лежащей на координатных осях OX и OY.
# Определить номер координатной четверти, в которой находится точка.

x = float(input("Введите x (не равный нулю): "))
y = float(input("Введите y (не равный нулю): "))

if x > 0 and y > 0:
    quarter = 1
elif x < 0 and y > 0:
    quarter = 2
elif x < 0 and y < 0:
    quarter = 3
else:
    quarter = 4

print("Координатная четверть:", quarter)
