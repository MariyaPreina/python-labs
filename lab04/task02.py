# Задача 2.
# Числа Фибоначчи: написать функцию, которая рекурсивно
# вычисляет n-е число Фибоначчи.
# Первые числа — 0 и 1; каждое следующее — сумма двух предыдущих: 0, 1, 1, 2, 3, 5, 8.
# Принцип: F(n) = F(n-1) + F(n-2); рекурсивно получаем два предыдущих ответа.
# n — номер с нуля, memo — словарь «номер: готовое число», чтобы не считать повторно.


def fibonacci(n, memo=None):
    # При первом вызове создаём словарь с базовыми ответами; дальше передаём его вместе с n.
    if memo is None:
        memo = {0: 0, 1: 1}
    # Каждое число вычисляем только один раз, затем берём готовое значение.
    if n not in memo:
        memo[n] = fibonacci(n - 1, memo) + fibonacci(n - 2, memo)
    return memo[n]

if __name__ == "__main__":
    n = int(input("Введите номер n (>= 0): "))
    if n < 0:
        print("n должно быть неотрицательным.")
    else:
        print("Число Фибоначчи:", fibonacci(n))
