# source — откуда, target — куда, auxiliary — вспомогательный стержень.
def hanoi(n, source, target, auxiliary):
    # Один диск переносим без дальнейших вызовов.
    if n == 1:
        print(f"Перенести диск 1: {source} -> {target}")
        return

    # Переносим n-1 верхних дисков на вспомогательный стержень.
    hanoi(n - 1, source, auxiliary, target)
    # Переносим освободившийся большой диск на целевой стержень.
    print(f"Перенести диск {n}: {source} -> {target}")
    # Переносим маленькую стопку со вспомогательного стержня на целевой.
    hanoi(n - 1, auxiliary, target, source)


if __name__ == "__main__":
    n = int(input("Введите количество дисков (>= 1): "))
    if n < 1:
        print("Количество дисков должно быть положительным.")
    else:
        hanoi(n, "A", "C", "B")
