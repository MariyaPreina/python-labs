# Задача 1.
# Факториал числа: написать функцию, которая рекурсивно
# вычисляет факториал заданного числа n.


def factorial(n):
    # 0! = 1 — здесь цепочка вызовов заканчивается.
    if n == 0:
        return 1
    # Сначала получаем (n-1)!, затем при возврате из вызова умножаем на n.
    return n * factorial(n - 1)


if __name__ == "__main__":
    n = int(input("Введите целое n (>= 0): "))
    if n < 0:
        print("n должно быть неотрицательным.")
    else:
        print("Факториал:", factorial(n))
