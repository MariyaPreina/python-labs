# Задача 8.
# Подсчёт количества цифр в числе: написать функцию, которая
# рекурсивно подсчитывает количество цифр в заданном числе.


def count_digits(number):
    # Минус не является цифрой. У нуля одна цифра.
    number = abs(number)
    if number < 10:
        return 1
    # // 10 убирает последнюю цифру; единица учитывает её в результате.
    return 1 + count_digits(number // 10)


if __name__ == "__main__":
    number = int(input("Введите целое число: "))
    print("Количество цифр:", count_digits(number))
