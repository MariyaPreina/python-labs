# Задача 1.
# Используя словесное описание, реализовать работу с очередью.
# Очередь работает по FIFO: первый добавленный элемент извлекается первым.

from collections import deque


def main():
    print("Добавляем в конец, извлекаем из начала очереди (FIFO).")
    q = deque()
    print("Очередь пуста:", "да" if not q else "нет")

    numbers = list(map(int, input("Введите целые числа через пробел: ").split()))

    # Добавляем справа, а извлекаем слева: первым выйдет первое введённое число.
    for value in numbers:
        q.append(value)
        print(f"Добавили {value}: {list(q)}")
    print("Слева — начало очереди, справа — конец.")

    # Проверка нужна: извлечение из пустой deque вызвало бы IndexError.
    if q:
        item = q.popleft()
        print("Извлечён первый элемент:", item)
        print("Очередь после извлечения:", list(q))
    else:
        print("Извлекать нечего: очередь пустая.")

    # Просмотр первого элемента не меняет очередь.
    if q:
        print("Первый элемент без удаления:", q[0])
    else:
        print("Очередь пуста: первого элемента нет.")

    print("Очередь пуста:", "да" if not q else "нет")
    print("Размер очереди:", len(q))
    target = int(input("Какое число проверить в оставшейся очереди? "))
    print(f"Есть ли число {target}:", "да" if target in q else "нет")

    # Обычный перебор не удаляет элементы.
    print("Элементы очереди:")
    for item in q:
        print(item)

    print("После перебора очередь не изменилась:", list(q))

    q.clear()
    print("После очистки:", list(q))
    print("Очередь пуста:", "да" if not q else "нет")


if __name__ == "__main__":
    main()
