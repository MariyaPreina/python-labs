# Задача 1.
# Используя словесное описание, реализовать работу с очередью.
# Очередь работает по FIFO: первый добавленный элемент извлекается первым.

from collections import deque


def main():
    q = deque()
    print("Очередь пуста:", not q)

    # Добавляем справа, а извлекаем слева: первым выйдет число 1.
    for value in [1, 2, 3]:
        q.append(value)
    print("После добавления:", list(q))

    # Проверка нужна: извлечение из пустой deque вызвало бы IndexError.
    if q:
        item = q.popleft()
        print("Извлечён элемент:", item)

    # Просмотр первого элемента не меняет очередь.
    if q:
        print("Первый элемент без удаления:", q[0])
    else:
        print("Очередь пуста: первого элемента нет.")

    print("Очередь пуста:", not q)
    print("Размер очереди:", len(q))
    print("Есть ли число 3:", 3 in q)

    # Обычный перебор не удаляет элементы.
    print("Элементы очереди:")
    for item in q:
        print(item)

    q.clear()
    print("После очистки:", list(q))
    print("Очередь пуста:", not q)


if __name__ == "__main__":
    main()
