# Задача 1.
# Используя словесное и визуальное описание, реализовать сортировку вставками.
# Элементы сортируются по возрастанию (равные значения допускаются).


def insertion_sort(numbers):
    # Перед каждым шагом элементы левее i уже отсортированы.
    for i in range(1, len(numbers)):
        # Сохраняем значение, иначе при сдвиге соседей оно будет затёрто.
        current = numbers[i]
        j = i - 1
        # Проверка j >= 0 выполняется первой и не даёт уйти за левый край.
        while j >= 0 and numbers[j] > current:
            # Сдвигаем больший элемент вправо, освобождая место для current.
            numbers[j + 1] = numbers[j]
            j -= 1
        # j остановился перед нужной позицией; при j=-1 вставляем в индекс 0.
        numbers[j + 1] = current


if __name__ == "__main__":
    numbers = list(map(int, input("Введите целые числа через пробел: ").split()))
    insertion_sort(numbers)
    print("Отсортированный массив:", numbers)
